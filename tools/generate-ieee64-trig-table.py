"""Generate a compact binary expansion of 2/pi for binary64 reduction."""
from decimal import Decimal, localcontext
from pathlib import Path

BITS = 1408
with localcontext() as context:
    context.prec = 500
    total = Decimal(13591409)
    multiplier, linear, power, k = 1, 13591409, 1, 6
    for i in range(1, 38):
        multiplier = multiplier * (k*k*k - 16*k) // (i*i*i)
        linear += 545140134
        power *= -262537412640768000
        total += Decimal(multiplier * linear) / power
        k += 12
    pi = 426880 * Decimal(10005).sqrt() / total
    value = int((2 / pi) * Decimal(2)**BITS)
    data = value.to_bytes(BITS // 8, 'little') + bytes(32)
    rows = ['; Generated by tools/generate-ieee64-trig-table.py; floor(2/pi * 2^1408), little endian']
    for offset in range(0, len(data), 16):
        rows.append('.byte ' + ', '.join(f'${byte:02x}' for byte in data[offset:offset+16]))
    target = Path(__file__).resolve().parents[1] / 'runtime/ieee64/trig-two-over-pi.inc'
    target.write_text('\n'.join(rows) + '\n')
