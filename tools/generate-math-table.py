"""Reproduce the binary32 Payne-Hanek constants using Decimal only."""
from decimal import Decimal, localcontext
from pathlib import Path

with localcontext() as context:
    context.prec = 180
    # Chudnovsky, 14 decimal digits per term; precision exceeds every table bit
    total = Decimal(13591409)
    multiplier, linear, power, k = 1, 13591409, 1, 6
    for i in range(1, 15):
        multiplier = multiplier * (k*k*k - 16*k) // (i*i*i)
        linear += 545140134
        power *= -262537412640768000
        total += Decimal(multiplier * linear) / power
        k += 12
    pi = 426880 * Decimal(10005).sqrt() / total
    rows = ['; Generated by tools/generate-math-table.py; e = -1 .. 127']
    for exponent in range(-1, 128):
        value = int((2 / pi) * Decimal(2)**(exponent + 73)) % (1 << 98)
        rows.append('.byte ' + ', '.join(f'${byte:02x}' for byte in value.to_bytes(14, 'little')))
    target = Path(__file__).resolve().parents[1] / 'runtime/math-two-over-pi.inc'
    target.write_text('\n'.join(rows) + '\n')
